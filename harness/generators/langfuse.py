"""Send a generator run to Langfuse: a trace per app, a span per tool call, and a
generation per model call carrying token usage.

Opt-in and best-effort. It does nothing unless `LANGFUSE_PUBLIC_KEY` and
`LANGFUSE_SECRET_KEY` are set, and it never raises: tracing must not fail a build.

Uses the ingestion API over stdlib HTTP rather than the SDK, so the generators keep
needing nothing from the lockfile.
"""

from __future__ import annotations

import base64
import json
import os
import urllib.error
import urllib.request
import uuid
from datetime import datetime, timezone
from pathlib import Path

# `timezone.utc`, not `datetime.UTC` (ruff UP017): these modules also run under the box's
# python3.9, where `datetime.UTC` does not exist.

TIMEOUT_SECONDS = 20
DEFAULT_BASE_URL = "https://cloud.langfuse.com"  # override with LANGFUSE_BASE_URL
# One tool call's arguments can be a whole file; Langfuse is for reading, not archiving.
MAX_VALUE_CHARS = 4_000


def _iso(epoch: float) -> str:
    return datetime.fromtimestamp(epoch, timezone.utc).isoformat()  # noqa: UP017


def _clip(value: object) -> object:
    if isinstance(value, str) and len(value) > MAX_VALUE_CHARS:
        return value[:MAX_VALUE_CHARS] + f"...[+{len(value) - MAX_VALUE_CHARS} chars]"
    if isinstance(value, dict):
        return {key: _clip(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_clip(item) for item in value]
    return value


# Credentials are read from the environment, falling back to a file, so a run traces by
# default instead of only when someone remembers to export three variables. In a cluster the
# environment is injected from a secret; locally this file is the same thing.
CREDENTIAL_FILE = Path(os.environ.get("LANGFUSE_ENV_FILE") or "~/.langfuse/acp-generators.env")
CREDENTIALS = ("LANGFUSE_PUBLIC_KEY", "LANGFUSE_SECRET_KEY", "LANGFUSE_BASE_URL")


def credentials() -> dict[str, str]:
    """Langfuse credentials from the environment, else from `CREDENTIAL_FILE`."""
    found = {name: os.environ[name] for name in CREDENTIALS if os.environ.get(name)}
    if found.get("LANGFUSE_PUBLIC_KEY") and found.get("LANGFUSE_SECRET_KEY"):
        return found
    path = CREDENTIAL_FILE.expanduser()
    if not path.is_file():
        return found
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        name = name.strip()
        if name in CREDENTIALS:
            found.setdefault(name, value.strip().strip("\"'"))
    return found


def _turn_input(call: dict, number: int) -> str:
    """What this turn was asked to do.

    The harness's system prompt only rides the first turn: it is identical on every call and
    is what a reader compares between harnesses, so it belongs in the trace once rather than
    fifteen times or nowhere.
    """
    request = call.get("request_preview") or f"turn {number}"
    system = call.get("system_preview")
    return f"SYSTEM PROMPT\n{system}\n\nTURN {number}\n{request}" if system else request


def _session(name: str) -> str:
    """Langfuse drops a sessionId over 200 chars, silently, and wants US-ASCII."""
    ascii_only = name.encode("ascii", "ignore").decode() or "evoweb"
    return ascii_only if len(ascii_only) <= 200 else ascii_only[:100] + "..." + ascii_only[-97:]


def _usage_details(usage: dict) -> dict:
    """Token counts for one call, cache included, summed the way the billing does."""
    details = {
        "input": usage.get("input_tokens"),
        "output": usage.get("output_tokens"),
        "cache_read_input_tokens": usage.get("cache_read_input_tokens"),
        "cache_creation_input_tokens": usage.get("cache_creation_input_tokens"),
    }
    details = {name: int(value) for name, value in details.items() if value is not None}
    if details:
        details["total"] = sum(details.values())
    return details


def enabled() -> bool:
    keys = credentials()
    return bool(keys.get("LANGFUSE_PUBLIC_KEY") and keys.get("LANGFUSE_SECRET_KEY"))


def publish(
    summary: dict,
    calls: list[dict],
    *,
    instruction: str,
    session_id: str | None = None,
    model_calls: list[dict] | None = None,
) -> str | None:
    """Send one app build as a Langfuse SESSION: one trace per turn, plus a summary trace.

    A session is one website generated by one harness, and a trace is one turn: the model
    call plus the tool calls it requested, nested under it. That is the shape that makes a session readable as a trajectory instead of a single
    opaque trace. Returns the summary trace id, or `None` when tracing is off or the send
    failed; the caller carries on either way.
    """
    keys = credentials()
    if not (keys.get("LANGFUSE_PUBLIC_KEY") and keys.get("LANGFUSE_SECRET_KEY")):
        return None
    now = datetime.now(timezone.utc).isoformat()  # noqa: UP017
    started = min(
        [call["started"] for call in calls] + [call["ts"] for call in model_calls or []],
        default=None,
    )
    ended = max((call["ended"] for call in calls if "ended" in call), default=None)
    session = _session(
        session_id or f"{summary['harness']}:task-{summary.get('task_id') or summary['index']}"
    )
    tags = [summary["harness"], summary["model"], "evoweb-generator"]
    batch: list[dict] = []

    turns = sorted(model_calls or [], key=lambda call: call["ts"])
    boundaries = [call["ts"] for call in turns]
    for number, call in enumerate(turns, 1):
        usage = call.get("usage") or {}
        trace_id, generation_id = str(uuid.uuid4()), str(uuid.uuid4())
        failed = (call.get("status") or 0) >= 400
        batch.append(
            {
                "id": str(uuid.uuid4()),
                "type": "trace-create",
                "timestamp": now,
                "body": {
                    "id": trace_id,
                    "name": f"generator:{summary['harness']}:turn-{number}",
                    "timestamp": _iso(call["ts"]),
                    "sessionId": session,
                    "userId": summary["harness"],
                    "input": _clip(_turn_input(call, number)),
                    "output": _clip(call.get("reply_preview") or ""),
                    "tags": tags,
                    "metadata": {"turn": number, "turns": len(turns), "status": call.get("status")},
                },
            }
        )
        batch.append(
            {
                "id": str(uuid.uuid4()),
                "type": "generation-create",
                "timestamp": now,
                "body": {
                    "id": generation_id,
                    "traceId": trace_id,
                    "name": f"model:{call.get('model') or summary['model']}",
                    "model": call.get("model") or summary["model"],
                    "startTime": _iso(call["ts"]),
                    "endTime": _iso(call["ts"] + call.get("duration_s", 0)),
                    "modelParameters": {
                        "max_tokens": call.get("max_tokens"),
                        "stream": call.get("stream"),
                    },
                    "input": _clip(_turn_input(call, number)),
                    "output": _clip(call.get("reply_preview") or ""),
                    # usageDetails, not the legacy `usage`: Anthropic reports input_tokens NET
                    # of the cache, so a cached call reads as 1 input token unless the cache
                    # keys travel with it.
                    "usageDetails": _usage_details(usage),
                    "metadata": {
                        "path": call.get("path"),
                        "messages": call.get("messages"),
                        "tools": call.get("tools"),
                    },
                    "level": "ERROR" if failed else "DEFAULT",
                    "statusMessage": f"HTTP {call.get('status')}" if failed else None,
                },
            }
        )
        # The tool calls this turn asked for: those starting before the next model call.
        upper = boundaries[number] if number < len(boundaries) else float("inf")
        for tool_call in calls:
            if not (call["ts"] <= tool_call["started"] < upper):
                continue
            tool_failed = tool_call.get("status") == "failed"
            batch.append(
                {
                    "id": str(uuid.uuid4()),
                    "type": "span-create",
                    "timestamp": now,
                    "body": {
                        "id": str(uuid.uuid4()),
                        "traceId": trace_id,
                        "parentObservationId": generation_id,
                        "name": f"{tool_call.get('kind') or 'tool'}:{tool_call.get('tool') or 'unknown'}",
                        "startTime": _iso(tool_call["started"]),
                        "endTime": _iso(tool_call["ended"]) if "ended" in tool_call else None,
                        "input": _clip(tool_call.get("args") or {"title": tool_call.get("title")}),
                        "output": _clip(tool_call.get("output") or tool_call.get("status")),
                        "level": "ERROR" if tool_failed else "DEFAULT",
                        "statusMessage": (
                            tool_call.get("output") or "tool call failed"
                        ).splitlines()[0][:300]
                        if tool_failed
                        else None,
                        "metadata": {
                            "paths": tool_call.get("paths") or [],
                            "title": tool_call.get("title"),
                        },
                    },
                }
            )

    # One more trace for the run itself, so the session carries the app's own numbers and the
    # final reply without a reader having to open every turn.
    summary_id = str(uuid.uuid4())
    batch.append(
        {
            "id": str(uuid.uuid4()),
            "type": "trace-create",
            "timestamp": now,
            "body": {
                "id": summary_id,
                "name": f"generator:{summary['harness']}:task-{summary.get('task_id') or summary['index']}",
                "timestamp": _iso(ended or started) if (ended or started) else now,
                "sessionId": session,
                "input": _clip(instruction),
                "output": _clip(summary.get("reply", "")),
                "tags": [*tags, "summary", *(["failed"] if summary.get("error") else [])],
                "metadata": {
                    key: summary[key]
                    for key in (
                        "harness",
                        "version",
                        "index",
                        "task_id",
                        "model",
                        "base_url",
                        "wall_clock_s",
                        "events",
                        "tool_calls",
                        "tools_used",
                        "tool_kinds",
                        "failed_tool_calls",
                        "files_written",
                        "system_prompt_appended",
                        "system_prompt_in_task",
                        "model_calls",
                        "failed_model_calls",
                        "model_seconds",
                        "input_tokens_total",
                        "input_tokens",
                        "output_tokens",
                        "cache_read_input_tokens",
                        "cache_creation_input_tokens",
                        "files_touched",
                        "shadowed_configs",
                        "error",
                    )
                    if key in summary
                },
            },
        }
    )
    if ended:
        batch[-1]["body"]["metadata"]["last_tool_call_at"] = _iso(ended)

    auth = base64.b64encode(
        f"{keys['LANGFUSE_PUBLIC_KEY']}:{keys['LANGFUSE_SECRET_KEY']}".encode()
    ).decode()
    url = keys.get("LANGFUSE_BASE_URL", DEFAULT_BASE_URL).rstrip("/") + "/api/public/ingestion"
    request = urllib.request.Request(
        url,
        data=json.dumps({"batch": batch}).encode(),
        headers={"Authorization": f"Basic {auth}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            # 207 is the normal answer: per-event statuses, some of which can fail.
            failures = (
                json.loads(response.read() or b"{}").get("errors") if response.status == 207 else []
            )
        if failures:
            print(f"langfuse rejected {len(failures)} of {len(batch)} events", flush=True)
        return summary_id
    except (urllib.error.URLError, OSError, ValueError) as error:
        print(f"langfuse publish failed ({type(error).__name__}: {error})", flush=True)
        return None
