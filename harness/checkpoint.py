"""Per-request checkpointing of a ladder.

A ladder runs hours in one pod; a node eviction anywhere loses the whole
run. This persists each completed request to S3 so a re-attempt resumes from the
last good request instead of restarting at request 1.

What defines "request K done" (and where it lives):
  - workspace files after request K  → snapshotted here (the ONLY new artifact)
  - conversation                  → turn_history in state.json; a harness resumes from it plus its own session file
  - scores + gate                 → carried in state.json here

S3 layout (checkpoints kept out of the result glob via the `_ckpt/` prefix):
  s3://{bucket}/{run_id}/{index:06d}/_ckpt/turn{n}/workspace.tgz
  s3://{bucket}/{run_id}/{index:06d}/_ckpt/turn{n}/state.json   ← written LAST

The `turn{n}` paths and the state.json keys (`turn`, `turn_results`, ...) keep their
original names so existing checkpoints and released traces stay readable.

state.json is the commit marker: it is uploaded only after workspace.tgz, so a
pod dying mid-upload leaves a request dir with no state.json, which detection skips.
"""

import json
import subprocess
from pathlib import Path


def _ckpt_prefix(s3_bucket: str, run_id: str, index: int) -> str:
    return f"s3://{s3_bucket}/{run_id}/{index:06d}/_ckpt"


def latest_checkpoint(s3_bucket: str, run_id: str, index: int) -> int:
    """Highest request K whose _ckpt/turn{K}/state.json exists, else 0.

    Only committed checkpoints (state.json present) count, so a half-uploaded
    request is never selected.
    """
    prefix = _ckpt_prefix(s3_bucket, run_id, index)
    out = subprocess.run(
        ["aws", "s3", "ls", "--recursive", f"{prefix}/"],
        capture_output=True,
        text=True,
    ).stdout
    best = 0
    for line in out.splitlines():
        # ".../\_ckpt/turn7/state.json"
        if line.rstrip().endswith("/state.json"):
            seg = [p for p in line.split("/") if p.startswith("turn")]
            if seg:
                try:
                    best = max(best, int(seg[-1][len("turn") :]))
                except ValueError:
                    pass
    return best


def save_checkpoint(
    s3_bucket,
    run_id,
    index,
    n,
    ws_dir,
    request_results,
    prev_request_passed,
    request_history=None,
    prev_fail_reason=None,
) -> None:
    """Snapshot request n. Atomic: workspace.tgz first, then state.json.

    node_modules is excluded — it is regenerated by npm install on resume, and
    including it would bloat the tarball from ~MB to hundreds of MB.
    Best-effort: any failure is logged by the caller and must not abort the run.
    """
    prefix = f"{_ckpt_prefix(s3_bucket, run_id, index)}/turn{n}"
    # workspace.tgz (streamed straight to S3, node_modules excluded)
    tar = subprocess.Popen(
        ["tar", "czf", "-", "--exclude=./node_modules", "--exclude=./.git", "-C", str(ws_dir), "."],
        stdout=subprocess.PIPE,
    )
    subprocess.run(
        ["aws", "s3", "cp", "-", f"{prefix}/workspace.tgz", "--quiet"],
        stdin=tar.stdout,
        check=True,
    )
    tar.stdout.close()
    if tar.wait() != 0:
        raise RuntimeError(f"tar of {ws_dir} failed for request {n}")
    # state.json LAST = commit marker
    # request_history is what makes a resumed HARNESS request multi-request: without it the ladder
    # continues with an empty conversation and still reports resumed_trajectory.
    state = {
        "turn": n,
        "prev_turn_passed": prev_request_passed,
        "turn_results": request_results,
        "turn_history": request_history or [],
        "prev_fail_reason": prev_fail_reason,
    }
    subprocess.run(
        ["aws", "s3", "cp", "-", f"{prefix}/state.json", "--quiet"],
        input=json.dumps(state),
        text=True,
        check=True,
    )


def restore_checkpoint(s3_bucket, run_id, index, k, ws_dir, local_dir):
    """Restore request k: workspace.tgz → ws_dir, run_turn{k}.json → trajectory.

    Returns (trajectory_path, request_results, prev_request_passed, request_history, prev_fail_reason),
    or None on any
    failure so the caller can fall back to a fresh start.
    """
    try:
        prefix = f"{_ckpt_prefix(s3_bucket, run_id, index)}/turn{k}"
        state = json.loads(
            subprocess.run(
                ["aws", "s3", "cp", f"{prefix}/state.json", "-"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout
        )

        # Unpack beside the workspace and swap only on success: deleting first meant a failed
        # restore left request k's files in place while the caller started again from request 1.
        ws_dir = Path(ws_dir)
        staging = ws_dir.with_name(ws_dir.name + ".restoring")
        if staging.exists():
            subprocess.run(["rm", "-rf", str(staging)], check=True)
        staging.mkdir(parents=True, exist_ok=True)
        download = subprocess.Popen(
            ["aws", "s3", "cp", f"{prefix}/workspace.tgz", "-", "--quiet"],
            stdout=subprocess.PIPE,
        )
        subprocess.run(["tar", "xzf", "-", "-C", str(staging)], stdin=download.stdout, check=True)
        download.stdout.close()
        if download.wait() != 0:
            subprocess.run(["rm", "-rf", str(staging)], check=False)
            return None
        if ws_dir.exists():
            subprocess.run(["rm", "-rf", str(ws_dir)], check=True)
        staging.rename(ws_dir)

        # trajectory for request k+1 = request k's run json, from the result path.
        # Request 1 writes to the run root; requests 2+ write under turn{k}/.
        base = f"s3://{s3_bucket}/{run_id}/{index:06d}"
        traj_s3 = (
            f"{base}/generation/run.json"
            if k == 1
            else f"{base}/turn{k}/generation/run_turn{k}.json"
        )
        # A harness resumes from history + its session file, so no run json is normally
        # there; a missing one must not fail the restore - it used to, after the workspace was
        # already replaced, so request 1 then ran on request k's app and was graded as request 1.
        traj_local = Path(local_dir) / f"resume_traj_turn{k}.json"
        if subprocess.run(["aws", "s3", "cp", traj_s3, str(traj_local), "--quiet"]).returncode != 0:
            traj_local = None

        return (
            str(traj_local) if traj_local else None,
            state["turn_results"],
            state["prev_turn_passed"],
            state.get("turn_history") or [],
            state.get("prev_fail_reason"),
        )
    except Exception:
        return None
